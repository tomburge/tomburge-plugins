import { join } from "node:path"
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { H, SP } from "../lib/harness.ts"
import { syncRegisters } from "../../hooks-handlers/lib/registers.ts"
const DIR = join(SP, "proj-registers"), P = DIR.replaceAll("\\", "/")
rmSync(DIR, { recursive: true, force: true })
mkdirSync(join(DIR, ".tomdlc"), { recursive: true })
const STATE = join(DIR, ".tomdlc/state.json")
const doc = (name: string) => join(DIR, ".tomdlc", name)
const read = (name: string) => (existsSync(doc(name)) ? readFileSync(doc(name), "utf8") : null)
let fails = 0, total = 0
async function run(hook: string, ev: object) {
  const p = Bun.spawn([process.execPath, join(H, hook)], { stdin: new TextEncoder().encode(JSON.stringify(ev)), stdout: "pipe" })
  const out = await new Response(p.stdout).text()
  return out ? JSON.parse(out) : {}
}
function expect(name: string, got: unknown, want: unknown) {
  total++
  if (JSON.stringify(got) !== JSON.stringify(want)) { fails++; console.log(`FAIL ${name}: got ${JSON.stringify(got)} want ${JSON.stringify(want)}`) }
}
const write = (file: string) => ({ cwd: P, tool_name: "Write", tool_input: { file_path: `${P}/.tomdlc/${file}` } })
const sync = async (s: any) => {
  writeFileSync(STATE, JSON.stringify(s))
  return run("sync-registers.ts", write("state.json"))
}
const validate = async (s: any) => {
  writeFileSync(STATE, JSON.stringify(s))
  return run("validate-state.ts", write("state.json"))
}
const note = (o: any) => String(o.hookSpecificOutput?.additionalContext ?? "")

const STAGES = ["plan", "requirements", "design", "develop", "test", "deploy", "maintain"]
const base: any = { project: "demo", currentStage: "plan", stages: Object.fromEntries(STAGES.map((s) => [s, { status: "not-started" }])), waivers: [], history: [] }

// ---- schemas for the decisions and practices registers
const decision = { id: "D-1", date: "2026-10-12", change: "CH-1", stage: "plan", question: "Which cloud?", answer: '"AWS | us-east-1"' }
const rule = { id: "RULE-1", kind: "learned", rule: "Run the linter before review", why: "two rounds lost to style", date: "2026-10-12" }
const valid = { ...base, decisions: [decision, { ...decision, id: "D-2", question: "Budget?", answer: "$50/month", default: true, confirmed: true }], practices: [rule] }
expect("valid decisions and practices", (await validate(valid)).decision ?? "allow", "allow")
const bad = async (name: string, s: any, frag: string) => {
  const r = await validate(s)
  expect(`${name}: blocked`, r.decision, "block")
  expect(`${name}: mentions ${frag}`, String(r.reason ?? "").includes(frag), true)
}
await bad("decision without answer", { ...base, decisions: [{ ...decision, answer: "" }] }, "needs `question` and `answer`")
await bad("bad decision id", { ...base, decisions: [{ ...decision, id: "Q1" }] }, "decisions[0].id")
await bad("duplicate decision id", { ...base, decisions: [decision, decision] }, "D-1 is used more than once")
await bad("bad decision stage", { ...base, decisions: [{ ...decision, stage: "kickoff" }] }, "decisions[0].stage")
await bad("learned rule without why", { ...base, practices: [{ ...rule, why: undefined }] }, "needs `why`")
await bad("preset without name", { ...base, practices: [{ ...rule, kind: "preset" }] }, "needs a `name`")
await bad("bad practice kind", { ...base, practices: [{ ...rule, kind: "style" }] }, "practices[0].kind")

// ---- views generated after a state.json write
const state: any = {
  ...base,
  risks: [
    { id: "R-2", type: "assumption", description: "Single currency", owner: "tom", status: "closed" },
    { id: "R-1", type: "risk", description: "Vendor API in beta", likelihood: "medium", impact: "high", treatment: "mitigate", action: "Contract tests", owner: "tom", status: "open", review: "2026-11-01" },
  ],
  findings: [
    { id: "F-1", stage: "develop", slice: "S-1", source: "reviewer", severity: "low", summary: "Typo", status: "open" },
    { id: "F-2", stage: "develop", source: "security-reviewer", severity: "high", summary: "Missing authz", status: "open" },
    { id: "F-3", stage: "design", source: "reviewer", severity: "medium", summary: "Old", status: "waived", waiver: "W-1" },
  ],
  waivers: [{ id: "W-1", stage: "design", stages: ["develop"], criterion: "Signed commits", reason: "Later", owner: "tom", expires: "2026-12-01" }],
  decisions: [decision],
}
const res = await sync(state)
expect("no note on a normal sync", note(res), "")
const risks = read("risks.md") ?? ""
expect("risks view written", risks.includes("# Risk register"), true)
expect("risks: open section has R-1 only", risks.split("## Closed")[0].includes("R-1") && !risks.split("## Closed")[0].includes("R-2"), true)
expect("risks: closed section has R-2", risks.split("## Closed")[1]?.includes("Single currency"), true)
expect("risks: do-not-edit notice", risks.startsWith("<!-- Generated by a TomDLC hook from `risks`"), true)
const findings = read("findings.md") ?? ""
expect("findings: open sorted by severity", findings.indexOf("F-2") < findings.indexOf("F-1"), true)
expect("findings: waived shows the waiver", /\| F-3 \|.*\| waived \| W-1 \|/.test(findings), true)
expect("waivers: every stage listed", (read("waivers.md") ?? "").includes("| W-1 | design, develop |"), true)
const decisions = read("decisions.md") ?? ""
expect("decisions: dated heading with change and stage", decisions.includes("## 2026-10-12 · CH-1 · plan"), true)
expect("decisions: pipes escaped, answer verbatim", decisions.includes('Answer: "AWS | us-east-1"'), true)
expect("no view for an absent register", [read("spikes.md"), read("promotions.md")], [null, null])
expect("unchanged state rewrites nothing", syncRegisters(DIR, state), [])
await sync({ ...state, risks: [{ ...state.risks[1], status: "closed" }] })
expect("risk closed: view follows", (read("risks.md") ?? "").includes("## Open (0)"), true)
await sync({ ...state, environments: { set: "dev-prod", promotions: [{ id: "P-1", to: "prod", build: "abc", status: "approved", requestedAt: "2026-10-12T10:00:00Z", approval: { text: "Approve", at: "2026-10-12T10:05:00Z" } }] } })
expect("promotions view", (read("promotions.md") ?? "").includes('| P-1 | prod | abc | approved | 2026-10-12 | "Approve" (2026-10-12) |'), true)
await sync({ ...state, spikes: [] })
expect("empty register still gets a view", read("spikes.md")?.includes("None."), true)
expect("invalid JSON leaves views alone", await (async () => {
  const before = read("risks.md")
  writeFileSync(STATE, "{ not json")
  await run("sync-registers.ts", write("state.json"))
  return read("risks.md") === before
})(), true)

// ---- decisions.md written before the register existed is kept until migrated
rmSync(doc("decisions.md"))
writeFileSync(doc("decisions.md"), "# Decisions\n\n## 2026-10-01 plan\n- Cloud? \"AWS\"\n")
const legacy = await sync({ ...state, decisions: undefined })
expect("legacy decisions.md kept", read("decisions.md")?.includes('Cloud? "AWS"'), true)
expect("orchestrator told to migrate decisions", note(legacy).includes("predates the `decisions` register"), true)

// ---- practices.md: only the rule sections are generated
const TEMPLATE = readFileSync(join(H, "..", "skills/orchestrator/reference/templates/practices.md"), "utf8")
const EOL = TEMPLATE.includes("\r\n") ? "\r\n" : "\n"
writeFileSync(doc("practices.md"), TEMPLATE.replace(`## Code style${EOL}`, `## Code style${EOL}Prettier, 2 spaces.${EOL}`))
const withRules = { ...state, practices: [rule, { id: "RULE-2", kind: "preset", name: "dependency-bump", shape: "dependency-update", rule: "develop light, test light", date: "2026-10-12" }] }
writeFileSync(STATE, JSON.stringify(withRules))
const drafted = await run("sync-registers.ts", write("practices.md"))
let practices = read("practices.md") ?? ""
expect("planner's draft gains the block quietly", note(drafted), "")
expect("prose kept", practices.includes("Prettier, 2 spaces."), true)
expect("learned rule rendered", practices.includes("- 2026-10-12: Run the linter before review (two rounds lost to style) (RULE-1)"), true)
expect("preset rendered", practices.includes("- **dependency-bump** (shape: dependency-update): develop light, test light (RULE-2)"), true)
expect("line endings kept", practices.includes("\r\n"), EOL === "\r\n")
expect("each rule heading once", ["## Mandated", "## Forbidden", "## Stage plan presets", "## Learned rules"].map((h) => practices.split(h).length - 1), [1, 1, 1, 1])
writeFileSync(doc("practices.md"), practices.replace("Run the linter before review", "Skip the linter"))
const edited = await run("sync-registers.ts", write("practices.md"))
expect("edit inside the block restored", (read("practices.md") ?? "").includes("Run the linter before review"), true)
expect("and the editor is told", note(edited).includes("restored from the register"), true)
await sync({ ...withRules, practices: [] })
practices = read("practices.md") ?? ""
expect("rules removed from the register leave the file", practices.includes("RULE-1"), false)
expect("prose survives a state write", practices.includes("Prettier, 2 spaces."), true)
rmSync(doc("practices.md"))
await sync(withRules)
expect("practices.md not created before the planner drafts it", read("practices.md"), null)
writeFileSync(doc("practices.md"), "# Project practices\n\n## Learned rules\n- 2026-10-01: Always pin versions (outage)\n")
const handRules = await sync({ ...withRules, practices: undefined })
expect("hand-written rules kept until migrated", read("practices.md")?.includes("Always pin versions"), true)
expect("orchestrator told to migrate rules", note(handRules).includes("written by hand"), true)

console.log(`${total} checks, ${fails} failures`)

process.exitCode = fails > 0 ? 1 : 0
